// Confirmation pass for the winner of smart-lab.mjs: the one-ply
// expected-value bot against every shipped preset, not just `balanced`.
// smart-lab answers "does this rule beat the bot it replaces?"; this answers
// "where would it rank if it shipped?".
import { runSimulation, createPreset, ThresholdBot, PRESETS, PRESET_NAMES } from '@farkle/bots';
import { DICE, DICE_PER_TURN } from '@farkle/engine';

const MATCHES = Number(process.argv[2] ?? 10000);
const BASE_SEED = 20260811;

const TARGETS = [1500, 3000, 8000];
const DICE_SETS = {
  ordinary: new Array(DICE_PER_TURN).fill(DICE['balanced']),
  cheat: new Array(DICE_PER_TURN).fill(DICE['cheat']),
  trinity: new Array(DICE_PER_TURN).fill(DICE['trinity']),
};

const EV_PARAMS = { ...PRESETS['balanced'], evBanking: true };
const OPPONENTS = PRESET_NAMES.filter((name) => name !== 'smart');

function pct(x) {
  return (x * 100).toFixed(1);
}

function seedFor(target, diceSetName, opponent) {
  let h = (BASE_SEED ^ target) >>> 0;
  const s = `ev|${diceSetName}|${opponent}`;
  for (let i = 0; i < s.length; i++) {
    h = (Math.imul(h, 16777619) ^ s.charCodeAt(i)) >>> 0;
  }
  return h >>> 0;
}

const started = Date.now();
console.log(`<!-- generated by scripts/dice-balance/smart-ev-roster.mjs, ${MATCHES} matches/cell -->`);
console.log(`\nsmart-ev's win rate against each shipped preset.\n`);
console.log(`| dice | target | ${OPPONENTS.join(' | ')} | mean |`);
console.log(`|---|---|${OPPONENTS.map(() => '---').join('|')}|---|`);

const all = [];
for (const diceSetName of Object.keys(DICE_SETS)) {
  for (const target of TARGETS) {
    const rates = [];
    for (const opponent of OPPONENTS) {
      const report = runSimulation({
        matches: MATCHES,
        seed: seedFor(target, diceSetName, opponent),
        target,
        loadoutA: DICE_SETS[diceSetName],
        loadoutB: DICE_SETS[diceSetName],
        makeA: (s) => new ThresholdBot('smart-ev', EV_PARAMS, s),
        makeB: (s) => createPreset(opponent, s),
      });
      rates.push(report.a.winRate);
      process.stderr.write(
        `[${((Date.now() - started) / 1000).toFixed(0)}s] ${diceSetName}/${target} vs ${opponent}: ${pct(report.a.winRate)}\n`,
      );
    }
    const mean = rates.reduce((s, x) => s + x, 0) / rates.length;
    all.push(mean);
    console.log(`| ${diceSetName} | ${target} | ${rates.map(pct).join(' | ')} | **${pct(mean)}** |`);
  }
}

console.log(`\nGrand mean across all 9 conditions: **${pct(all.reduce((s, x) => s + x, 0) / all.length)}**`);
process.stderr.write(`done in ${((Date.now() - started) / 1000).toFixed(0)}s\n`);
