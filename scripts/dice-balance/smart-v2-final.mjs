// Final confirmation for docs/researches/2026-08-11-smart-v2.md: the winning
// recipe from smart-v2-lab.mjs (evBanking + evKeepSelection, optionally with
// evCapToTarget — controlled by the CLI flag below) at high match count,
// compared to both `balanced` and the old `smart` preset, plus a full roster
// pass the same shape as smart-ev-roster.mjs.
import { runSimulation, createPreset, ThresholdBot, PRESETS, PRESET_NAMES } from '@farkle/bots';
import { DICE, DICE_PER_TURN } from '@farkle/engine';

const MATCHES = Number(process.argv[2] ?? 20000);
const WITH_CAP = process.argv.includes('--cap');
const BASE_SEED = 20260811;

const TARGETS = [1500, 3000, 8000];
const DICE_SETS = {
  ordinary: new Array(DICE_PER_TURN).fill(DICE['balanced']),
  cheat: new Array(DICE_PER_TURN).fill(DICE['cheat']),
  trinity: new Array(DICE_PER_TURN).fill(DICE['trinity']),
};

const SMART_V2_PARAMS = {
  ...PRESETS['balanced'],
  evBanking: true,
  evKeepSelection: true,
  ...(WITH_CAP ? { evCapToTarget: true } : {}),
};
const OPPONENTS = PRESET_NAMES.filter((name) => name !== 'smart').concat(['smart']);

function pct(x) {
  return (x * 100).toFixed(1);
}
function seedFor(tag, target, diceSetName, opponent) {
  let h = (BASE_SEED ^ target) >>> 0;
  const s = `${tag}|${diceSetName}|${opponent}`;
  for (let i = 0; i < s.length; i++) {
    h = (Math.imul(h, 16777619) ^ s.charCodeAt(i)) >>> 0;
  }
  return h >>> 0;
}

function makeSmartV2(seed) {
  return new ThresholdBot('smart-v2', SMART_V2_PARAMS, seed);
}

const started = Date.now();
const label = WITH_CAP ? 'smart-v2 (evBanking+evKeepSelection+evCapToTarget)' : 'smart-v2 (evBanking+evKeepSelection)';
console.log(`<!-- generated by scripts/dice-balance/smart-v2-final.mjs, ${MATCHES} matches/cell -->`);
console.log(`\n${label} — win rate against every shipped preset (old \`smart\` included).\n`);
console.log(`| dice | target | ${OPPONENTS.join(' | ')} | mean |`);
console.log(`|---|---|${OPPONENTS.map(() => '---').join('|')}|---|`);

const all = [];
for (const diceSetName of Object.keys(DICE_SETS)) {
  for (const target of TARGETS) {
    const rates = [];
    for (const opponent of OPPONENTS) {
      const report = runSimulation({
        matches: MATCHES,
        seed: seedFor('roster', target, diceSetName, opponent),
        target,
        loadoutA: DICE_SETS[diceSetName],
        loadoutB: DICE_SETS[diceSetName],
        makeA: (s) => makeSmartV2(s),
        makeB: (s) => createPreset(opponent, s),
      });
      rates.push(report.a.winRate);
      process.stderr.write(
        `[${((Date.now() - started) / 1000).toFixed(0)}s] ${diceSetName}/${target} vs ${opponent}: ${pct(report.a.winRate)}\n`,
      );
    }
    const mean = rates.reduce((s, x) => s + x, 0) / rates.length;
    all.push(mean);
    console.log(`| ${diceSetName} | ${target} | ${rates.map(pct).join(' | ')} | **${pct(mean)}** |`);
  }
}
console.log(`\nGrand mean across all 9 conditions: **${pct(all.reduce((s, x) => s + x, 0) / all.length)}**`);
process.stderr.write(`done in ${((Date.now() - started) / 1000).toFixed(0)}s\n`);
